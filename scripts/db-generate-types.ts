/**
 * pnpm db:generate
 *
 * Regenerates src/types/database.ts from the real database schema via
 * `supabase gen types typescript`. There is no live Supabase project in
 * this sandbox, so src/types/database.ts is currently a hand-written
 * mirror of supabase/migrations/*.sql. This script is what a real
 * environment should run to replace it with the CLI's actual output.
 *
 * It never overwrites the existing file with empty/failed output --
 * the hand-written version stays authoritative until generation
 * genuinely succeeds.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

import { commandExists, fail, runCapture } from "./_lib/shell";

const OUTPUT_PATH = path.join(process.cwd(), "src", "types", "database.ts");

const HEADER = `// AUTO-GENERATED by \`pnpm db:generate\` (supabase gen types typescript).
// Do not edit by hand -- re-run \`pnpm db:generate\` instead.
// If this header disappears, someone reverted to the hand-written stub in
// its place -- see scripts/db-generate-types.ts.

`;

function main(): void {
  if (!commandExists("supabase")) {
    fail(
      [
        "[db:generate] Cannot generate types: the Supabase CLI is not installed.",
        "",
        "Fix:",
        "  1. npm install -g supabase        (or: brew install supabase/tap/supabase)",
        "  2. Either:",
        "       a) supabase link --project-ref <your-project-ref>   (generate from the remote project), or",
        "       b) supabase start                                   (generate from a local dev stack)",
        "  3. Re-run: pnpm db:generate",
        "",
        `Until then, ${path.relative(process.cwd(), OUTPUT_PATH)} stays as the hand-written mirror of supabase/migrations/*.sql.`,
      ].join("\n"),
    );
  }

  console.log("[db:generate] Supabase CLI found. Trying `supabase gen types typescript --linked`...");
  let output = runCapture("supabase", ["gen", "types", "typescript", "--linked"]);

  if (!output) {
    console.log(
      "[db:generate] --linked unavailable (project not linked, or not reachable). Trying --local...",
    );
    output = runCapture("supabase", ["gen", "types", "typescript", "--local"]);
  }

  if (!output) {
    fail(
      [
        "[db:generate] Could not generate types: the project isn't linked and no local Supabase",
        "stack is reachable.",
        "",
        "Fix ONE of the following, then re-run `pnpm db:generate`:",
        "  - Linked remote project: supabase link --project-ref <your-project-ref>",
        "  - Local dev stack:       supabase start   (requires Docker)",
        "",
        `${path.relative(process.cwd(), OUTPUT_PATH)} was NOT modified.`,
      ].join("\n"),
    );
  }

  writeFileSync(OUTPUT_PATH, HEADER + output);
  console.log(`[db:generate] Wrote ${path.relative(process.cwd(), OUTPUT_PATH)}`);
}

main();
